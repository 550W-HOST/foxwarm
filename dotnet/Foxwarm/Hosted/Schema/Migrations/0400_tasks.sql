CREATE TABLE tasks (
    tenant_id integer NOT NULL,
    id text COLLATE "C" NOT NULL,
    title text COLLATE "C" NOT NULL,
    description text COLLATE "C",
    status text COLLATE "C" NOT NULL CHECK (status IN ('open', 'active', 'completed', 'cancelled')),
    "parentTaskId" text COLLATE "C",
    "createdByKind" text COLLATE "C" NOT NULL DEFAULT 'session' CHECK ("createdByKind" IN ('session', 'user')),
    "createdBySessionId" text COLLATE "C",
    "ownerSessionId" text COLLATE "C",
    result text COLLATE "C",
    "createdAt" bigint NOT NULL,
    "updatedAt" bigint NOT NULL,
    "completedAt" bigint,
    "cancelledAt" bigint,
    "completionNotificationStatus" text COLLATE "C",
    "assignmentNotificationStatus" text COLLATE "C",
    "previousOwnerSessionId" text COLLATE "C",
    "previousOwnerNotificationStatus" text COLLATE "C",
    "assignmentRevision" bigint NOT NULL DEFAULT 0,
    "attachedSessionId" text COLLATE "C",
    "legacyGoalSessionId" text COLLATE "C",
    "reminderLastSeq" bigint,
    "reminderMessageCount" bigint NOT NULL DEFAULT 0,
    "ownerAssignedAt" bigint,
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, "parentTaskId") REFERENCES tasks (tenant_id, id),
    UNIQUE (tenant_id, "legacyGoalSessionId")
);
SELECT foxwarm_tenant_table('tasks', 'SELECT, INSERT, UPDATE');
CREATE INDEX tasks_status ON tasks (tenant_id, status, "updatedAt" DESC NULLS LAST, id ASC NULLS FIRST);
CREATE INDEX tasks_parent ON tasks (tenant_id, "parentTaskId", "createdAt" ASC NULLS FIRST, id ASC NULLS FIRST);
CREATE INDEX tasks_self_owned ON tasks (tenant_id, "createdBySessionId", "ownerSessionId", status, "createdAt", id);

CREATE TABLE task_notes (
    tenant_id integer NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    "taskId" text COLLATE "C" NOT NULL,
    "authorKind" text COLLATE "C" NOT NULL DEFAULT 'session' CHECK ("authorKind" IN ('session', 'user')),
    "sessionId" text COLLATE "C",
    text text COLLATE "C" NOT NULL,
    "createdAt" bigint NOT NULL,
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, "taskId") REFERENCES tasks (tenant_id, id)
);
SELECT foxwarm_tenant_table('task_notes', 'SELECT, INSERT');
CREATE INDEX task_notes_task ON task_notes (tenant_id, "taskId", id DESC NULLS LAST);
