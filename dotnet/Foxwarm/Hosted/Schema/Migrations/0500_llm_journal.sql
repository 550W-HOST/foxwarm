-- reader-floor: 2
-- The LLM request journal (ILlmJournalStore): the file journal's tables with tenant keys.
-- JSON stays text byte for byte. `seq` replaces SQLite's rowid order; the tenant's single
-- journal writer assigns it in commit order.

CREATE TABLE llm_journal_metadata (
    tenant_id integer NOT NULL,
    key text COLLATE "C" NOT NULL,
    value text COLLATE "C" NOT NULL,
    PRIMARY KEY (tenant_id, key)
);
SELECT foxwarm_tenant_table('llm_journal_metadata', 'SELECT, INSERT, UPDATE, DELETE');

-- Content-addressed and deduplicated per tenant; retention deletes objects no retained
-- request or attempt references.
CREATE TABLE llm_journal_objects (
    tenant_id integer NOT NULL,
    object_id text COLLATE "C" NOT NULL,
    object_kind text COLLATE "C" NOT NULL,
    payload text COLLATE "C" NOT NULL,
    created_at bigint NOT NULL,
    PRIMARY KEY (tenant_id, object_id)
);
SELECT foxwarm_tenant_table('llm_journal_objects', 'SELECT, INSERT, DELETE');

CREATE TABLE llm_journal_requests (
    tenant_id integer NOT NULL,
    seq bigint GENERATED BY DEFAULT AS IDENTITY,
    request_id text COLLATE "C" NOT NULL,
    session_id text COLLATE "C",
    purpose text COLLATE "C" NOT NULL,
    iteration bigint NOT NULL,
    created_at bigint NOT NULL,
    prompt_object_id text COLLATE "C" NOT NULL,
    tool_schema_object_id text COLLATE "C" NOT NULL,
    requested_model_key text COLLATE "C" NOT NULL,
    prompt_cache_key_hash text COLLATE "C" NOT NULL,
    message_count bigint NOT NULL,
    checkpoint_message_ids_json text COLLATE "C",
    base_request_id text COLLATE "C",
    common_prefix_length bigint,
    appended_message_ids_json text COLLATE "C",
    delta_depth bigint NOT NULL,
    PRIMARY KEY (tenant_id, request_id)
);
SELECT foxwarm_tenant_table('llm_journal_requests', 'SELECT, INSERT, DELETE');
CREATE INDEX llm_journal_requests_session
    ON llm_journal_requests (tenant_id, session_id, created_at, seq);
CREATE INDEX llm_journal_requests_created
    ON llm_journal_requests (tenant_id, created_at, request_id);
CREATE INDEX llm_journal_requests_base
    ON llm_journal_requests (tenant_id, base_request_id) WHERE base_request_id IS NOT NULL;

-- The objects a request's manifest names (prompt, tool schema and the message identities
-- in its checkpoint or appended list), extracted at admission so retention can find
-- unreferenced objects without reading manifest JSON.
CREATE TABLE llm_journal_request_objects (
    tenant_id integer NOT NULL,
    request_id text COLLATE "C" NOT NULL,
    object_id text COLLATE "C" NOT NULL,
    PRIMARY KEY (tenant_id, request_id, object_id)
);
SELECT foxwarm_tenant_table('llm_journal_request_objects', 'SELECT, INSERT, DELETE');
CREATE INDEX llm_journal_request_objects_object
    ON llm_journal_request_objects (tenant_id, object_id);

CREATE TABLE llm_journal_attempt_starts (
    tenant_id integer NOT NULL,
    seq bigint GENERATED BY DEFAULT AS IDENTITY,
    event_id text COLLATE "C" NOT NULL,
    request_id text COLLATE "C" NOT NULL,
    attempt bigint NOT NULL,
    started_at bigint NOT NULL,
    concrete_model_id text COLLATE "C" NOT NULL,
    virtual_model_key text COLLATE "C",
    provider_type text COLLATE "C" NOT NULL,
    semantic_payload_sha256 text COLLATE "C" NOT NULL,
    prompt_object_id text COLLATE "C",
    PRIMARY KEY (tenant_id, event_id)
);
SELECT foxwarm_tenant_table('llm_journal_attempt_starts', 'SELECT, INSERT, DELETE');
CREATE INDEX llm_journal_attempt_starts_request
    ON llm_journal_attempt_starts (tenant_id, request_id, attempt, seq);
CREATE INDEX llm_journal_attempt_starts_prompt
    ON llm_journal_attempt_starts (tenant_id, prompt_object_id) WHERE prompt_object_id IS NOT NULL;

CREATE TABLE llm_journal_attempt_results (
    tenant_id integer NOT NULL,
    seq bigint GENERATED BY DEFAULT AS IDENTITY,
    event_id text COLLATE "C" NOT NULL,
    request_id text COLLATE "C" NOT NULL,
    attempt bigint NOT NULL,
    completed_at bigint NOT NULL,
    outcome text COLLATE "C" NOT NULL,
    result_json text COLLATE "C",
    error_json text COLLATE "C",
    PRIMARY KEY (tenant_id, event_id)
);
SELECT foxwarm_tenant_table('llm_journal_attempt_results', 'SELECT, INSERT, DELETE');
CREATE INDEX llm_journal_attempt_results_request
    ON llm_journal_attempt_results (tenant_id, request_id, attempt);
CREATE INDEX llm_journal_attempt_results_seq
    ON llm_journal_attempt_results (tenant_id, seq);

-- The usage ledger and the redaction statistics are kept by retention, so the runtime role
-- can't delete or rewrite them.
CREATE TABLE llm_usage (
    tenant_id integer NOT NULL,
    request_id text COLLATE "C" NOT NULL,
    attempt bigint NOT NULL,
    completed_at bigint NOT NULL,
    session_id text COLLATE "C",
    purpose text COLLATE "C" NOT NULL,
    model_key text COLLATE "C" NOT NULL,
    provider_key text COLLATE "C" NOT NULL,
    provider_type text COLLATE "C" NOT NULL,
    virtual_model_key text COLLATE "C",
    cached_tokens bigint,
    input_tokens bigint,
    output_tokens bigint,
    cost double precision,
    PRIMARY KEY (tenant_id, request_id, attempt)
);
SELECT foxwarm_tenant_table('llm_usage', 'SELECT, INSERT');
CREATE INDEX llm_usage_time ON llm_usage (tenant_id, completed_at);

CREATE TABLE llm_redaction (
    tenant_id integer NOT NULL,
    request_id text COLLATE "C" NOT NULL,
    attempt bigint NOT NULL,
    completed_at bigint NOT NULL,
    session_id text COLLATE "C",
    purpose text COLLATE "C" NOT NULL,
    model_key text COLLATE "C" NOT NULL,
    provider_key text COLLATE "C" NOT NULL,
    provider_type text COLLATE "C" NOT NULL,
    virtual_model_key text COLLATE "C",
    failure_kind text COLLATE "C",
    detected bigint NOT NULL,
    literal bigint NOT NULL,
    detected_labels text COLLATE "C" NOT NULL,
    literal_labels text COLLATE "C" NOT NULL,
    slots bigint NOT NULL,
    detected_slots bigint NOT NULL,
    cached_slots bigint NOT NULL,
    detector_calls bigint NOT NULL,
    detection_ms double precision NOT NULL,
    omitted bigint NOT NULL,
    PRIMARY KEY (tenant_id, request_id, attempt)
);
SELECT foxwarm_tenant_table('llm_redaction', 'SELECT, INSERT');
CREATE INDEX llm_redaction_time ON llm_redaction (tenant_id, completed_at);
