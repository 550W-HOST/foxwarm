import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
if (process.versions.unicode !== '17.0') {
  throw new Error(`Unicode 17.0 is required for Source lowercase generation/comparison; use Node 24.21.0 (running Node ${process.versions.node}, Unicode ${process.versions.unicode}).`);
}
const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../Foxwarm/Sessions');
const map = [], cased = [], ignorable = [];
for (let code = 0; code <= 0x10ffff; code++) {
  const text = String.fromCodePoint(code), lower = [...text.toLowerCase()].map(ch => ch.codePointAt(0));
  if (lower.length === 1 && lower[0] !== code) map.push([code, lower[0] - code]);
  if (/\p{Cased}/u.test(text)) cased.push(code);
  if (/\p{Case_Ignorable}/u.test(text)) ignorable.push(code);
}
function ranges(values) {
  const result = [];
  for (const value of values) {
    if (result.length && result.at(-1)[1] + 1 === value) result.at(-1)[1] = value;
    else result.push([value, value]);
  }
  return result;
}
const mappings = [];
for (let i = 0; i < map.length;) {
  let end = i + 1, step = end < map.length && map[end][1] === map[i][1] ? map[end][0] - map[i][0] : 1;
  if (step !== 1 && step !== 2) step = 1;
  while (end < map.length && map[end][1] === map[i][1] && map[end][0] - map[end - 1][0] === step) end++;
  mappings.push([map[i][0], map[end - 1][0], step, map[i][1]]); i = end;
}
for (const [name, rows, type] of [['Mappings', mappings, '(int Start, int End, int Step, int Delta)'], ['Cased', ranges(cased), '(int Start, int End)'], ['Ignorable', ranges(ignorable), '(int Start, int End)']]) {
  fs.writeFileSync(path.join(target, `SourceStringLower.${name}.cs`), `// Generated by dotnet/scripts/generate-source-lowercase.mjs (Unicode ${process.versions.unicode}).\nnamespace Foxwarm.Sessions;\n\ninternal static partial class SourceStringLower\n{\n    private static readonly ${type}[] ${name} =\n    [\n${Array.from({length: Math.ceil(rows.length / 4)}, (_, i) => '        ' + rows.slice(i * 4, i * 4 + 4).map(row => '(' + row.join(', ') + '),').join(' ')).join('\n')}\n    ];\n}\n`);
}
