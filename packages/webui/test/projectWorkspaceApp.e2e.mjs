import { appE2eRuntime } from '../../../test/app-e2e/runtime.mjs'
import { waitForWebUiReady } from './webuiReadiness.mjs'
import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import path from 'node:path'
import puppeteer from 'puppeteer-core'

const { baseUrl, tokenFile } = appE2eRuntime()
const chromium = process.env.FOXWARM_E2E_CHROMIUM || '/usr/bin/chromium'

test('project mode keeps settings and management in its shell and retains work across navigation', async () => {
  const token = (await readFile(tokenFile, 'utf8')).trim()
  const projectDirectory = path.dirname(process.env.FOXWARM_E2E_TOOL_FILE)
  const browser = await puppeteer.launch({ executablePath: chromium, headless: true, args: ['--no-sandbox'] })
  const page = await browser.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    await page.setViewport({ width: 1440, height: 900 })
    await page.goto(`${baseUrl}/#token=${encodeURIComponent(token)}`, { waitUntil: 'networkidle2' })
    await waitForWebUiReady(page)
    await page.evaluate(() => { window.location.hash = 'setup' })
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent.trim() === 'Project'), { timeout: 15000 })
    const clickVisible = async (text, selector = 'button') => {
      const found = await page.evaluate((label, query) => {
        const element = [...document.querySelectorAll(query)].find(item => item.textContent.trim() === label && item.getClientRects().length > 0)
        if (!element) return false
        element.click()
        return true
      }, text, selector)
      assert.equal(found, true, `visible control ${text}`)
    }
    const projects = () => page.evaluate(async () => (await (await fetch('/api/projects')).json()).projects)
    const assertProjectShell = async () => {
      assert.equal(await page.$eval('[data-project-workspace]', element => element.getClientRects().length > 0), true, 'Project shell stays visible')
      assert.equal(await page.$eval('[data-project-workspace] [aria-label="Projects"]', element => element.getClientRects().length > 0), true, 'Project navigation stays visible')
      assert.equal(await page.evaluate(() => localStorage.getItem('foxwarm_workspace_mode_v1')), 'project')
      assert.equal(await page.$$eval('[data-workbench-content-tab]', elements => elements.every(element => !element.getClientRects().length || getComputedStyle(element).visibility !== 'visible')), true, 'classic content must stay hidden')
    }
    await clickVisible('Project')
    await page.waitForSelector('[data-project-workspace]', { visible: true })
    await clickVisible('New project')
    await page.type('input[placeholder="Optional"]', 'Integration project')
    await page.type('input[placeholder="Use node default"]', projectDirectory)
    await clickVisible('Create project')
    await page.waitForSelector('[aria-label="New tab"]', { visible: true })
    await clickVisible('New Agent tab')
    await page.waitForFunction(async () => (await (await fetch('/api/projects')).json()).projects[0]?.sessions[0]?.tabs.some(tab => tab.type === 'agent' && tab.state === 'ready'), { timeout: 20000 })
    await page.waitForSelector('.foxwarm-model-selector-trigger', { visible: true, timeout: 20000 })
    await page.click('[aria-label="New tab"]')
    await page.waitForSelector('[role="menuitem"]', { visible: true })
    const menuHitTargets = await page.$$eval('[role="menuitem"]', items => items.map(item => {
      const rect = item.getBoundingClientRect()
      return document.elementFromPoint(rect.left + rect.width / 2, rect.top + rect.height / 2)?.closest('[role="menuitem"]') === item
    }))
    assert.deepEqual(menuHitTargets, [true, true, true, true], 'new tab menu must stay above the chat header and remain clickable')
    await page.click('[role="menuitem"]')
    await page.waitForFunction(async () => (await (await fetch('/api/projects')).json()).projects[0]?.sessions[0]?.tabs.filter(tab => tab.type === 'agent' && tab.state === 'ready').length === 2, { timeout: 20000 })
    let [project] = await projects()
    const agents = project.sessions[0].tabs.filter(tab => tab.type === 'agent')
    assert.equal(new Set(agents.map(tab => tab.resourceId)).size, 2)
    assert.equal(project.rootPath, projectDirectory)

    await page.waitForFunction(() => [...document.querySelectorAll('[data-project-workspace] [role="textbox"][contenteditable="true"]')].some(element => element.getClientRects().length), { timeout: 15000 })
    const classicLayout = await page.evaluate(() => localStorage.getItem('foxwarm_workbench_state_v4'))
    await page.evaluate(() => {
      window.projectAgentRoot = [...document.querySelectorAll('[data-project-workspace] .foxwarm-chat-root')].find(element => element.getClientRects().length)
      window.projectAgentEditor = window.projectAgentRoot.querySelector('[role="textbox"]')
      window.projectAgentEditor.focus()
    })
    await page.keyboard.type('Keep this unsent project draft')
    await page.evaluate(() => window.projectAgentRoot.querySelector('.foxwarm-model-selector-trigger').click())
    await page.waitForSelector('button[aria-label="Configure models"]', { visible: true, timeout: 15000 })
    await page.click('button[aria-label="Configure models"]')
    await page.waitForSelector('[data-project-auxiliary-content="system:setup"] [data-setup-section="models"] [data-editor-ready="true"]', { visible: true, timeout: 20000 })
    await page.waitForFunction(() => !!document.activeElement?.closest('[data-project-auxiliary-content="system:setup"] [data-monaco-model-uri="inmemory://foxwarm/setup/project/foxwarm-models.yaml"]'), { timeout: 15000 })
    await assertProjectShell()
    assert.equal(await page.$$eval('[data-project-auxiliary-tab="system:setup"]', tabs => tabs.length), 1, 'model settings use a singleton Project tab')
    assert.equal(await page.evaluate(() => window.projectAgentRoot.isConnected && !window.projectAgentRoot.getClientRects().length), true, 'Agent remains mounted while settings are open')
    await page.click('[data-project-auxiliary-tab="system:setup"] button[aria-label^="Close "]')
    await page.waitForFunction(() => window.projectAgentRoot.getClientRects().length > 0)
    assert.deepEqual(await page.evaluate(() => ({ sameEditor: window.projectAgentEditor === window.projectAgentRoot.querySelector('[role="textbox"]'), draft: window.projectAgentEditor.textContent.replace(/\u200B/g, '') })), { sameEditor: true, draft: 'Keep this unsent project draft' })

    await page.click('[data-project-workspace] button[aria-label="Settings"]')
    await page.waitForSelector('[data-project-auxiliary-content="system:setup"]', { visible: true })
    await assertProjectShell()
    await page.click('[data-project-workspace] button[aria-label="Agents"]')
    await page.waitForSelector('[data-project-auxiliary-content="system:agents"] h1', { visible: true, timeout: 15000 })
    await assertProjectShell()
    const openedNodes = await page.evaluate(() => {
      const button = [...document.querySelectorAll('[data-project-auxiliary-content="system:agents"] button')].find(element => element.textContent.includes('Nodes') && element.textContent.includes('protocol-compatible execution'))
      button?.click()
      return !!button
    })
    assert.equal(openedNodes, true, 'Agents can open Nodes inside Project')
    await page.waitForSelector('[data-project-auxiliary-content="system:nodes"]', { visible: true })
    await page.waitForFunction(() => [...document.querySelectorAll('[data-project-auxiliary-content="system:nodes"] button')].some(button => button.textContent.trim() === 'New nodes'), { timeout: 15000 })
    await assertProjectShell()
    await clickVisible('History', '[data-project-workspace] aside button')
    await page.waitForSelector('[data-project-workspace] [data-history-query-input]', { visible: true })
    await page.type('[data-project-workspace] [data-history-query-input]', 'Unsubmitted history search')
    await assertProjectShell()
    await clickVisible('Back to work session')
    await page.waitForFunction(() => window.projectAgentRoot.getClientRects().length > 0)
    await clickVisible('History', '[data-project-workspace] aside button')
    await page.waitForSelector('[data-project-workspace] [data-history-query-input]', { visible: true })
    assert.equal(await page.$eval('[data-project-workspace] [data-history-query-input]', input => input.value), 'Unsubmitted history search', 'History retains its draft across Project navigation')
    await clickVisible('Back to work session')
    await page.waitForSelector('[data-project-workspace] [aria-label="Unassigned conversations"] button[title="main"]', { visible: true })
    await page.click('[data-project-workspace] [aria-label="Unassigned conversations"] button[title="main"]')
    await page.waitForSelector('[data-project-auxiliary-content="chat:main"] .foxwarm-chat-root', { visible: true, timeout: 15000 })
    await page.waitForFunction(() => document.querySelector('[data-project-auxiliary-content="chat:main"]')?.textContent.includes('main message 2'), { timeout: 15000 })
    await assertProjectShell()
    assert.equal(await page.evaluate(() => window.projectAgentRoot.isConnected && !window.projectAgentRoot.getClientRects().length), true, 'opening an unassigned conversation preserves the Project Agent')
    await clickVisible('Back to work session')
    await page.waitForFunction(() => window.projectAgentRoot.getClientRects().length > 0)
    assert.deepEqual(await page.evaluate(() => ({ sameEditor: window.projectAgentEditor === window.projectAgentRoot.querySelector('[role="textbox"]'), draft: window.projectAgentEditor.textContent.replace(/\u200B/g, '') })), { sameEditor: true, draft: 'Keep this unsent project draft' })
    assert.equal(await page.evaluate(() => localStorage.getItem('foxwarm_workbench_state_v4')), classicLayout, 'Project management must preserve the classic workbench layout')

    await page.setViewport({ width: 390, height: 844 })
    await page.click('[data-project-workspace] button[aria-label="Hide sidebar"]')
    await page.evaluate(() => window.projectAgentRoot.querySelector('.foxwarm-model-selector-trigger').click())
    await page.waitForSelector('button[aria-label="Configure models"]', { visible: true })
    await page.click('button[aria-label="Configure models"]')
    await page.waitForSelector('[data-project-auxiliary-content="system:setup"] [data-setup-section="models"] [data-editor-ready="true"]', { visible: true, timeout: 15000 })
    assert.equal(await page.$eval('[data-project-workspace]', element => element.getClientRects().length > 0), true, 'mobile model settings keep the Project shell')
    await clickVisible('Back to work session')
    await page.waitForFunction(() => window.projectAgentRoot.getClientRects().length > 0)
    assert.equal(await page.evaluate(() => window.projectAgentEditor.isConnected && window.projectAgentEditor.textContent.replace(/\u200B/g, '')), 'Keep this unsent project draft')
    await page.setViewport({ width: 1440, height: 900 })
    await page.click('[data-project-workspace] button[aria-label="Show projects"]')

    await page.click('[aria-label="New tab"]')
    await clickVisible('terminal', '[role="menuitem"]')
    await page.waitForFunction(async () => (await (await fetch('/api/projects')).json()).projects[0]?.sessions[0]?.tabs.some(tab => tab.type === 'terminal' && tab.resourceId), { timeout: 30000 })
    ;[project] = await projects()
    const terminalId = project.sessions[0].tabs.find(tab => tab.type === 'terminal').resourceId
    const terminal = await page.evaluate(async id => (await (await fetch(`/api/terminals/${encodeURIComponent(id)}`)).json()).terminal, terminalId)
    assert.equal(terminal.nodeId, 'master')
    assert.equal(terminal.cwd, projectDirectory)

    await page.click('[aria-label="New tab"]')
    await clickVisible('code', '[role="menuitem"]')
    await page.waitForSelector('iframe[data-foxwarm-vscode-web-frame]', { visible: true, timeout: 20000 })
    await page.evaluate(() => { window.projectCodeFrame = document.querySelector('iframe[data-foxwarm-vscode-web-frame]') })
    const codeUrl = await page.$eval('iframe[data-foxwarm-vscode-web-frame]', frame => frame.src)
    assert.ok(codeUrl.includes(`workspaceId=${project.sessions[0].id}`))
    await clickVisible('Terminal', '[role="tab"]')
    await clickVisible('Code', '[role="tab"]')
    assert.equal(await page.evaluate(() => window.projectCodeFrame === document.querySelector('iframe[data-foxwarm-vscode-web-frame]')), true)

    await page.click('button[aria-label="Settings"]')
    await page.waitForSelector('[data-project-auxiliary-content="system:setup"]', { visible: true })
    await assertProjectShell()
    assert.equal(await page.evaluate(() => window.projectCodeFrame === document.querySelector('iframe[data-foxwarm-vscode-web-frame]') && window.projectCodeFrame.isConnected), true, 'settings keep the existing Code iframe mounted')
    assert.equal(await page.evaluate(async id => (await fetch(`/api/terminals/${encodeURIComponent(id)}`)).status, terminalId), 200, 'settings leave the terminal running')
    await page.click('[data-project-auxiliary-content="system:setup"] [data-setup-tab="appearance"]')
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent.trim() === 'Original' && button.getClientRects().length), { timeout: 15000 })
    await clickVisible('Original')
    await clickVisible('Project')
    await page.waitForSelector('[data-project-workspace]', { visible: true })
    assert.equal(await page.evaluate(async id => (await fetch(`/api/terminals/${encodeURIComponent(id)}`)).status, terminalId), 200)
    await page.reload({ waitUntil: 'networkidle2' })
    await page.waitForSelector('[data-project-workspace]', { visible: true, timeout: 20000 })
    await page.waitForFunction(async id => (await (await fetch('/api/projects')).json()).projects[0]?.sessions[0]?.tabs.some(tab => tab.resourceId === id), { timeout: 10000 }, terminalId)
    assert.equal(await page.evaluate(async id => (await fetch(`/api/terminals/${encodeURIComponent(id)}`)).status, terminalId), 200)
    await page.evaluate(async id => { await fetch(`/api/terminals/${encodeURIComponent(id)}`, { method: 'DELETE' }) }, terminalId)
    const countAfterDelete = await page.evaluate(async () => (await (await fetch('/api/terminals')).json()).terminals.length)
    await page.reload({ waitUntil: 'networkidle2' })
    await page.waitForSelector('[data-project-workspace]', { visible: true, timeout: 20000 })
    await clickVisible('Terminal', '[role="tab"]')
    await page.waitForFunction(() => document.body.textContent.includes('This terminal has ended.'), { timeout: 15000 })
    assert.equal(await page.evaluate(async () => (await (await fetch('/api/terminals')).json()).terminals.length), countAfterDelete)
    assert.deepEqual(errors, [])
  } finally {
    await browser.close()
  }
})
