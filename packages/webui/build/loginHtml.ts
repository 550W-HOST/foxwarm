import { readFile, writeFile, rename } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'
import type { Plugin } from 'vite'

const webui = new URL('../', import.meta.url)

/** Generate the independently served login page from the canonical theme and fox sources. */
export async function renderLoginHtml(): Promise<string> {
  const [html, css, loaderCss, drawingJson, bundle] = await Promise.all([
    readFile(new URL('src/login.html', webui), 'utf8'),
    readFile(new URL('src/login.css', webui), 'utf8'),
    readFile(new URL('src/components/FoxLoaders.css', webui), 'utf8'),
    readFile(new URL('src/components/foxDrawing.json', webui), 'utf8'),
    build({ entryPoints: [fileURLToPath(new URL('src/login.ts', webui))], bundle: true, format: 'iife', platform: 'browser', target: 'es2020', minify: true, write: false, logLevel: 'silent' }),
  ])
  const { paths: fox, viewBox } = JSON.parse(drawingJson)
  const lines = (draw: boolean) => {
    const path = (name: string, at: number, className = '') => `<path d="${fox[name]}" ${draw ? `pathLength="1" style="--fw-fox-delay:${at}ms"` : ''} class="${draw ? 'fw-fox-draw' : ''} ${className}"/>`
    return `<g class="fw-fox-body">${path('back',130)}${path('haunch',450,'fw-fox-mid')}${path('tailTop',310)}${path('tailTip',525,'fw-fox-thin')}</g><g class="fw-fox-head">${path('head',0)}${path('chest',410,'fw-fox-mid')}${path('eyeLeft',575,'fw-fox-mid')}${path('eyeRight',600,'fw-fox-mid')}<ellipse cx="51" cy="64.5" rx="4.6" ry="3.4" transform="rotate(-20 51 64.5)" class="fw-fox-nose"/></g>`
  }
  const art = `<svg viewBox="${viewBox}" width="220" height="220" class="fw-fox fw-fox-cub fw-fox-live" aria-hidden="true">${lines(true)}</svg>`
  const spinner = `<svg viewBox="${viewBox}" width="20" height="20" class="fw-fox fw-fox-spinner" aria-hidden="true"><g class="fw-fox-faint-all">${lines(false)}</g><path d="${fox.loop}" pathLength="1" class="fw-fox-comet"/></svg>`
  const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="none" stroke="#d07b42" stroke-width="5" stroke-linecap="round" stroke-linejoin="round">${lines(false).replace(/class="fw-fox-nose"/, 'fill="#d07b42"')}</svg>`
  const script = bundle.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')
  return '<!-- Generated by build/loginHtml.ts from src/login.* and the shared theme/fox sources. -->\n' + html
    .replace('<!-- foxwarm-login-head -->', `<link rel="icon" href="data:image/svg+xml,${encodeURIComponent(icon)}"><style>${loaderCss}\n${css}</style><script>${script}</script>`)
    .replace('<!-- foxwarm-login-fox -->', art)
    .replace('<!-- foxwarm-login-spinner -->', spinner)
}

export function loginHtmlPlugin(): Plugin {
  return {
    name: 'foxwarm-login-html',
    async buildStart() {
      const target = new URL('public/login.html', webui)
      const html = await renderLoginHtml()
      if (await readFile(target, 'utf8').catch(() => '') === html) return
      // The running backend serves this file directly; never expose a partial write.
      const temporary = new URL('public/.login.html.tmp', webui)
      await writeFile(temporary, html)
      await rename(temporary, target)
    },
    configureServer(server) {
      server.middlewares.use(async (req, res, next) => {
        if (req.url?.split('?')[0] !== '/login.html') return next()
        try { res.setHeader('Content-Type', 'text/html; charset=utf-8'); res.setHeader('Cache-Control', 'no-store'); res.end(await renderLoginHtml()) }
        catch (error) { next(error) }
      })
    },
  }
}
